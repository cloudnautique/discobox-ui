#!/usr/bin/env python3
"""Derive the native palette directly from the pinned backend's brand tokens."""
import argparse
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
source = root / "discobox/assets/brand/tokens.json"
target = root / "Sources/DiscoboxDesktop/BrandTokens.swift"
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
raw = source.read_bytes()
tokens = json.loads(raw)
lines = ["// Generated by scripts/generate-brand.py; do not edit consumer values.",
         "// Source: discobox/assets/brand/tokens.json · SHA-256 " + hashlib.sha256(raw).hexdigest(),
         "import SwiftUI", "import AppKit", "", "enum BrandTokens {"]
for name, token in tokens["color"].items():
    parts = name.split("-")
    prop = parts[0] + "".join(p.title() for p in parts[1:])
    dark = token["$value"].removeprefix("#")
    light = token["$extensions"]["ai.discobox"].get("light", token["$value"]).removeprefix("#")
    lines.append(f"    static let {prop} = adaptive(light: 0x{light}, dark: 0x{dark})")
lines.extend(["", "    private static func adaptive(light: UInt32, dark: UInt32) -> Color {",
              "        Color(nsColor: NSColor(name: nil) { appearance in",
              "            let value = appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua ? dark : light",
              "            return NSColor(red: CGFloat((value >> 16) & 255) / 255, green: CGFloat((value >> 8) & 255) / 255, blue: CGFloat(value & 255) / 255, alpha: 1)",
              "        })", "    }", "}", ""])
output = "\n".join(lines)
if args.check:
    if not target.exists() or target.read_text() != output:
        raise SystemExit("Brand tokens changed. Run make brand-tokens and review the generated palette.")
else:
    target.write_text(output)
